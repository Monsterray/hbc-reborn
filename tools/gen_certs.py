#!/usr/bin/env python3
"""Regenerate sdk/wiiupdate/certs.h from the Mozilla CA bundle.

    curl -sSLf -o cacert.pem https://curl.se/ca/cacert.pem
    python3 tools/gen_certs.py cacert.pem > sdk/wiiupdate/certs.h

Only the roots that api.github.com and GitHub's download hosts chain to (now
or plausibly next) are kept, as DER, so the Wii parses them quickly and HBC
needs no PEM parser.
"""
import base64
import sys

WANTED = [
    "USERTrust ECC Certification Authority",
    "USERTrust RSA Certification Authority",
    "Sectigo Public Server Authentication Root E46",
    "Sectigo Public Server Authentication Root R46",
    "DigiCert Global Root G2",
    "ISRG Root X1",
    "ISRG Root X2",
]

text = open(sys.argv[1], encoding="utf-8").read().splitlines()
certs = {}
for i, line in enumerate(text):
    if line.strip() in WANTED and i + 2 < len(text) and text[i + 1].startswith("="):
        j = i + 2
        while not text[j].startswith("-----BEGIN"):
            j += 1
        k = j
        while not text[k].startswith("-----END"):
            k += 1
        certs[line.strip()] = base64.b64decode("".join(text[j + 1:k]))

missing = [n for n in WANTED if n not in certs]
if missing:
    sys.exit("missing roots: " + ", ".join(missing))

print("/* Root certificates for api.github.com and GitHub's download hosts, from")
print(" * the Mozilla CA bundle (curl.se), as DER, one after another.")
print(" * Generated by tools/gen_certs.py; do not edit. */")
print("#pragma once\n")
print("static const unsigned short WIIUPDATE_CA_SIZES[] = {")
for name in WANTED:
    print(f"\t{len(certs[name])},\t/* {name} */")
print("};\n")
print("static const unsigned char WIIUPDATE_CA_DER[] = {")
for name in WANTED:
    print(f"\t/* {name} */")
    der = certs[name]
    for at in range(0, len(der), 12):
        print("\t" + " ".join(f"0x{b:02x}," for b in der[at:at + 12]))
print("};")
