#!/usr/bin/env python3
"""Write tests/README.md: every test, one line each, from its own docstring.

Each line is the test's path and the first sentence of its module docstring
(a test app: the first comment in its main.c). To change a line, change the
test's docstring and run this again; tests/host/test_tests_index.py fails when
the index is out of date.

  python tests/lib/make_index.py           # rewrite tests/README.md
  python tests/lib/make_index.py --check   # exit 1 if it is out of date
"""
import argparse
import ast
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
TESTS = ROOT / "tests"
OUT = TESTS / "README.md"

LAYERS = [
    ("host", "This PC, no Wii",
     "`python -m unittest discover -s tests/host -p 'test_*.py'` runs every `test_*.py`; "
     "CI runs the same. `python tests/host/run_parallel.py` runs them all at once (about 20 s "
     "instead of 2 minutes). Each also runs alone: `python tests/host/test_mii.py`."),
    ("dolphin", "Dolphin, in a throwaway profile",
     "`python tests/dolphin/<test>.py`. One Dolphin at a time: a second cannot bind port 4299. "
     "`python tests/dolphin/run_all.py [--special]` runs every one in a row, builds what is "
     "missing, reruns a failure once and prints a table with seconds. A profile starts empty "
     "(Dolphin makes its 128 MB SD image on the first boot), so a test's cost is the boot, "
     "about 9 s, plus its waits: poll HBCS with `waits.wait_until` rather than `time.sleep`."),
    ("wii", "A real Wii",
     "Through the bench queue (see [CONTRIBUTING.md](../CONTRIBUTING.md#testing)). "
     "Tests that can hang IOS are never run unattended. `wii_checks.ensure_hbc` skips the DOL send "
     "when this build's HBC already runs (`fresh=True` for a test that needs HBC just started); "
     "`wii_netbench.py` and `netblock_run.py` are on-demand benches, not part of a routine run."),
    ("apps", "The Wii, sent by the tests above",
     "`make -C tests/apps/<app>`; each shows a text console on the TV. "
     "`OGC=libogc2` builds need devkitPPC r41-2 (`$DEVKITPRO/devkitPPC-r41-2` or `DEVKITPPC_R41`)."),
    ("lib", "Imported by the tests",
     "`sys.path.insert(0, str(root / \"tests\" / \"lib\")); import testenv` puts `tools/` "
     "and every folder here on the path."),
]


def first_sentence(text):
    text = " ".join(re.split(r"\n\s*\n", text.strip())[0].split())  # first paragraph
    m = re.match(r"(.+?[.!?])(\s|$)", text)
    s = m.group(1) if m else text
    return s.replace("|", "\\|")


def py_summary(path):
    doc = ast.get_docstring(ast.parse(path.read_bytes().decode("utf-8")))
    return first_sentence(doc) if doc else ""


def c_summary(folder):
    for name in ("main.c", "test.c", "preview.py"):
        p = folder / name
        if not p.exists():
            continue
        if p.suffix == ".py":
            return py_summary(p)
        src = p.read_bytes().decode("utf-8", "replace")
        m = re.match(r"\s*/\*(.*?)\*/", src, re.S)
        if m:
            body = re.sub(r"^\s*\* ?", "", m.group(1), flags=re.M)
            return first_sentence(body)
        lines = []
        for line in src.splitlines():
            if not line.startswith("//"):
                if lines:
                    break
                continue
            lines.append(line[2:].strip())
        return first_sentence(" ".join(lines)) if lines else ""
    return ""


def entries(layer):
    folder = TESTS / layer
    rows = []
    for p in sorted(folder.iterdir()):
        if p.name.startswith(("_", ".")) or p.name == "README.md":
            continue
        if p.is_dir():
            rows.append((p.name + "/", c_summary(p)))
        elif p.suffix == ".py":
            rows.append((p.name, py_summary(p)))
        elif p.suffix in (".sh", ".c"):
            src = p.read_bytes().decode("utf-8", "replace")
            com = [l.lstrip("#/ ").strip() for l in src.splitlines()[1:6] if l.startswith(("#", "//"))]
            rows.append((p.name, first_sentence(" ".join(com)) if com else ""))
    return rows


def render():
    out = ["# Tests", "",
           "Every test, by where it runs, with what it covers. Search this page for a",
           "feature or a file name. Generated by `tests/lib/make_index.py` from each",
           "test's own docstring: edit the docstring, then run the script.", ""]
    for layer, where, how in LAYERS:
        out += [f"## {layer}/: {where}", "", how, "", "| Test | What it covers |", "| --- | --- |"]
        for name, summary in entries(layer):
            out.append(f"| [`{name}`]({layer}/{name}) | {summary or '(no docstring yet)'} |")
        out.append("")
    return "\n".join(out)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="exit 1 if tests/README.md is out of date")
    args = ap.parse_args(argv)
    text = render()
    if args.check:
        same = OUT.exists() and OUT.read_bytes().decode("utf-8") == text
        print("tests/README.md is up to date" if same else
              "tests/README.md is out of date: run python tests/lib/make_index.py")
        return 0 if same else 1
    OUT.write_bytes(text.encode("utf-8"))
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
